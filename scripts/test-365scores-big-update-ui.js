'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8');
const matchSummary = html.match(/function renderScores365MatchContent\(details,tab\)\s*\{([\s\S]*?)\n  \}\n  function renderScores365MatchPanel/);
assert.ok(matchSummary, 'Resumo do Livescore 365Scores deve existir.');
const summary = matchSummary[1];
assert.ok(summary.includes('details.clock'), 'Resumo deve usar o minuto retornado pela 365Scores.');
assert.ok(summary.includes("?'INT'"), 'Resumo deve reconhecer intervalo.');
assert.ok(!summary.includes('details.round'), 'Resumo não deve mostrar rodada.');
assert.ok(!summary.includes('details.venue'), 'Resumo não deve mostrar estádio.');
assert.ok(!summary.includes('chartEventsCount'), 'Resumo não deve mostrar contagem de finalizações.');
assert.ok(!summary.includes('match-livescore-score'), 'O Livescore não deve repetir o placar principal da agenda.');
assert.ok(!summary.includes('details.score'), 'O resumo do Livescore não deve renderizar placar.');
assert.ok(html.includes('homeScore = cleanScore'), 'A agenda deve sanitizar placares negativos.');
assert.ok(html.includes('fim de jogo|full time|match ended'), 'Evento de fim de jogo deve ser filtrado da lista do Livescore.');
assert.ok(html.includes('function scores365KickoffForEvent(event)'), 'Horário 365Scores deve ter helper próprio.');
assert.ok(html.includes("timeZone:'America/Sao_Paulo'"), 'Horário deve ser convertido para Brasília.');
assert.ok(html.includes('kickoff.text||e.timeText'), 'Horário da 365Scores deve ter fallback para a agenda.');
assert.ok(html.includes('imagecache.365scores.com/image/upload') && html.includes('/v1/Competitors/'), 'Escudos 365Scores por ID devem continuar integrados.');
console.log('PASSOU: Livescore compacto, minutos, intervalo, placares seguros, horário 365Scores e escudos por ID.');
