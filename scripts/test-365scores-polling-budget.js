'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const service=fs.readFileSync(path.join(root,'365scores-service.js'),'utf8');
const engine=fs.readFileSync(path.join(root,'multi-api-engine.js'),'utf8');
const pkg=require('../package.json');
assert.equal(pkg.version,'0.22.9');
assert.match(service,/ttlMs:\s*90_000/,'Detalhes da partida devem usar cache de 90s.');
assert.match(service,/ttlMs:\s*10\s*\*\s*60_000/,'Classificação deve usar cache de 10min.');
assert.match(html,/},90000\);/,'Partida aberta deve atualizar a cada 90s.');
assert.match(html,/scores365AgendaClockTimer=setInterval\(\(\)=>void refreshScores365AgendaClockBatch\(\),120000\)/,'Agenda deve percorrer jogos a cada 120s.');
assert.match(html,/const batchSize=1/,'No máximo uma partida de fundo por ciclo.');
assert.match(html,/if\(modalOpen\)return/,'Polling da agenda pausa com partida aberta.');
assert.match(html,/await loadScores365MatchData\(event,false,true\)/,'Polling automático deve respeitar cache, sem force.');
assert.match(html,/SCORES365_MATCH_SEARCH_ATTEMPTS_KEY/,'Busca sem resultado deve ter cooldown por partida.');
assert.match(html,/6\*60\*60\*1000/,'Cooldown da busca deve ser de seis horas.');
assert.match(service,/registerUpstreamPause\(status, retryAfterHeader/,'Pausa deve responder a status HTTP reais.');
assert.match(service,/parseRetryAfterMs\(retryAfterHeader\)/,'HTTP 429 deve respeitar Retry-After.');
assert.match(service,/365SCORES_ACCESS_PAUSED/,'HTTP 403 deve pausar o adaptador.');
assert.match(service,/365SCORES_RATE_PAUSED/,'HTTP 429 deve pausar o adaptador.');
assert.doesNotMatch(service,/reserveRequest\(['"]365scores['"]/,'365Scores não deve reservar consumo em quota local.');
assert.doesNotMatch(service,/dailySoftLimit:\s*200|perMinuteLimit:\s*12/,'Não deve haver quota fixa artificial de 200/dia ou 12/min.');
assert.match(html,/sem limite diário ou por minuto imposto pelo aplicativo/,'O Admin deve explicar a ausência de teto local fixo.');
assert.match(html,/respostas HTTP 429\/403 acionam pausa automática/,'O Admin deve explicar a pausa baseada em respostas reais.');
assert.doesNotMatch(html,/teto local do protótipo: 12 chamadas\/minuto e 200\/dia/i,'A interface não deve divulgar o antigo teto local.');
assert.match(engine,/quota:\s*null/,'O catálogo do provider 365Scores não deve declarar cota artificial.');
console.log('PASSOU: sem quota artificial 365Scores; cache, polling moderado, fila, pausa HTTP 429/403 e Retry-After.');
