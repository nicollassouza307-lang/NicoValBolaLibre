#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const pkg=require('../package.json');
assert.equal(pkg.version,'0.22.12');
const logoStart=html.indexOf('function logoMarkup('),logoEnd=html.indexOf('\n  function theSportsDbLocalKey',logoStart);
assert.ok(logoStart>=0&&logoEnd>logoStart);
const logo=html.slice(logoStart,logoEnd);
assert.ok(logo.indexOf('      apiUrl,')<logo.indexOf('      githubLogo'), 'Imagem 365Scores deve vir antes do fallback GitHub.');
assert.match(html,/function scores365CompetitionLogoFor/,'Competições precisam de URL 365Scores por ID.');
assert.match(html,/function competitionLogoForGroup\(group\)[\s\S]*scores365CompetitionLogoFor/,'Grupos de competições devem tentar 365Scores.');
assert.match(html,/async function hydrateTheSportsDbBadge[\s\S]*?return ''; \/\* V0\.22\.0/,'TheSportsDB deve estar desativada no fluxo de escudos.');
assert.match(html,/async function hydrateTheSportsDbLeagueBadge[\s\S]*?return; \/\* V0\.22\.0/,'TheSportsDB deve estar desativada no fluxo de competições.');
assert.match(html,/scores365TeamLogoFor\(e,'home'\)/,'Escudos da 365Scores precisam alimentar cartões.');
assert.doesNotMatch(html,/scores365TeamLogoFor\(e,'home'\) \|\| e\.homeBadge/,'Não deve priorizar escudo de agenda antes do fallback GitHub.');
assert.match(html,/background:transparent;padding:2px/,'Somente escudos dos times devem perder o fundo branco.');
console.log('PASSOU: 365Scores prioritária para clubes/competições, GitHub como fallback e TheSportsDB aposentada do fluxo visual ativo.');
