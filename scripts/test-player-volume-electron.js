'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const main = fs.readFileSync(path.join(root, 'electron/main.js'), 'utf8');
const preload = fs.readFileSync(path.join(root, 'electron/preload.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const builder = require('../build/electron-builder.config.js');
assert.match(main, /ipcMain\.handle\('nvb:player-volume'/);
assert.match(main, /framesInSubtree/);
assert.match(main, /document\.querySelector\('#playerScreen iframe'\)/);
assert.match(main, /createDynamicsCompressor/);
assert.match(main, /threshold\.value\s*=\s*-8/);
assert.match(main, /roots\.has\(current\)/, 'o booster deve ficar restrito à árvore do iframe do player');
assert.match(preload, /setPlayerVolume:\s*percent\s*=>\s*ipcRenderer\.invoke\('nvb:player-volume'/);
assert.match(html, /min="100" max="300" step="10"/);
assert.match(html, /id="playerVolumeReset"/);
assert.match(html, /id="playerVolumeWarning"/);
assert.match(html, /percent>200/);
assert.match(html, /frame\.addEventListener\('load'/);
assert.match(html, /setPlayerVolume\(savedBoost\)/, 'o nível salvo deve ser reaplicado após o player carregar');
assert.ok(builder.extraResources.some(item => item.from.endsWith(`${path.sep}team-name-normalizer.js`)));
assert.ok(builder.extraResources.some(item => item.from.endsWith(`${path.sep}scores365-standings.js`)));
console.log('PASSOU: Volume Booster Electron restrito ao player, limitador, controle 100-300%, reaplicação após load e assets do instalador.');
